import { EventType } from "@prisma/client";
import { prisma } from "@/lib/db";
import { buildEventWhereClause } from "@/lib/events/queries";
import { formatInAppTz, getCalendarDaysBetween } from "@/lib/time";

export interface ReportPayload {
  header: {
    title: string;
    universityName: string;
    facultyName: string;
    facultyCode: string;
    department: string;
    from: string;
    to: string;
    generatedDate: string;
  };
  summary: {
    totalHosted: number;
    totalAttended: number;
    totalBusyDays: number;
    totalEvents: number;
    departmentsInvolved: string[];
  };
  events: Array<{
    id: string;
    dateFormatted: string;
    startAt: string;
    endAt: string;
    allDay: boolean;
    title: string;
    type: EventType;
    role: string;
    organizer: string;
    location: string;
    department: string;
    description: string | null;
    attachmentUrl: string | null;
  }>;
  footer: string;
}

export async function buildFacultyReport(params: {
  facultyId: string;
  from: Date;
  to: Date;
  type?: string;
  department?: string;
  title?: string;
}): Promise<ReportPayload> {
  const faculty = await prisma.faculty.findUniqueOrThrow({
    where: { id: params.facultyId },
  });

  // SEC1 & SEC11: Strictly scoped to params.facultyId
  const where = buildEventWhereClause(params.facultyId, {
    from: params.from,
    to: params.to,
    type: params.type,
    department: params.department,
  });

  const rawEvents = await prisma.event.findMany({
    where,
    orderBy: { startAt: "asc" },
  });

  let totalHosted = 0;
  let totalAttended = 0;
  const busyDays = new Set<string>();
  const deptSet = new Set<string>();

  const rows = rawEvents.map((ev) => {
    if (ev.type === EventType.HOSTED) totalHosted += 1;
    if (ev.type === EventType.ATTENDED) totalAttended += 1;
    if (ev.type === EventType.BUSY) {
      for (const d of getCalendarDaysBetween(ev.startAt, ev.endAt)) {
        busyDays.add(d);
      }
    }
    if (ev.department?.trim()) {
      deptSet.add(ev.department.trim());
    }

    return {
      id: ev.id,
      dateFormatted: formatInAppTz(
        ev.startAt,
        ev.allDay ? "dd MMM yyyy '(All day)'" : "dd MMM yyyy, hh:mm a"
      ),
      startAt: ev.startAt.toISOString(),
      endAt: ev.endAt.toISOString(),
      allDay: ev.allDay,
      title: ev.title,
      type: ev.type,
      role: ev.role ?? "-",
      organizer: ev.organizer ?? "-",
      location: ev.location ?? "-",
      department: ev.department ?? "-",
      description: ev.description ?? null,
      attachmentUrl: ev.attachmentUrl ?? null,
    };
  });

  const generatedDate = formatInAppTz(new Date(), "dd MMM yyyy");

  return {
    header: {
      title: params.title || "Semester Activity Report",
      universityName: process.env.UNIVERSITY_NAME || "Dayananda Sagar University",
      facultyName: faculty.fullName,
      facultyCode: faculty.facultyCode,
      department: faculty.department,
      from: formatInAppTz(params.from, "yyyy-MM-dd"),
      to: formatInAppTz(params.to, "yyyy-MM-dd"),
      generatedDate,
    },
    summary: {
      totalHosted,
      totalAttended,
      totalBusyDays: busyDays.size,
      totalEvents: rows.length,
      departmentsInvolved: Array.from(deptSet).sort(),
    },
    events: rows,
    footer: `Generated by FacultyPulse on ${generatedDate}. Records are self-reported by the faculty member.`,
  };
}
